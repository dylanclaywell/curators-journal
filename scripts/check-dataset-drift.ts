/**
 * Has the wiki moved since the datasets were generated, and if so, what now.
 *
 * Driven by `.github/workflows/dataset-drift.yml` on a schedule, but written to
 * run identically by hand — `npm run check:drift` is safe anywhere, because
 * opening a PR takes an explicit flag.
 *
 * This lives in TypeScript rather than inline in the workflow for one reason
 * beyond readability: the exit-code contract is defined in `lib/wiki.ts`, and
 * expressing it again as bare numbers in a YAML shell step would be the same
 * mistake that predicate already records — logic written twice, the copies
 * drifting apart. Here the constants are imported, so they cannot.
 *
 * It also means the drift check is type-checked and linted like everything else
 * in `scripts/`, where a `run:` block is checked by nothing at all.
 *
 *   npm run check:drift             # report only; never writes anything
 *   npm run check:drift -- --open-pr   # regenerate, verify, and open the PR
 */
import { spawnSync } from 'node:child_process'
import type { SpawnSyncOptions } from 'node:child_process'
import { fileURLToPath } from 'node:url'

import { EXIT_FINDING, EXIT_OK, EXIT_UNREACHABLE } from './lib/wiki.ts'

const root = fileURLToPath(new URL('..', import.meta.url))

const BRANCH = 'chore/dataset-refresh'
const TITLE = 'chore: refresh the quest and diary datasets from the wiki'

/** GitHub renders these as annotations; harmless noise anywhere else. */
const notice = (message: string) => console.log(`::notice::${message}`)

function run(
  command: string,
  args: string[],
  options: SpawnSyncOptions = {},
): number {
  const result = spawnSync(command, args, {
    cwd: root,
    stdio: 'inherit',
    // npm and gh are shell scripts on Windows; the generators are not, but
    // passing shell for all of them keeps this runnable on a dev machine.
    shell: process.platform === 'win32',
    ...options,
  })
  if (result.error) throw result.error
  return result.status ?? 1
}

function capture(command: string, args: string[]): string {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: 'utf8',
    shell: process.platform === 'win32',
  })
  return (result.stdout ?? '').trim()
}

/** One generator, in `--check` mode. Returns its exit code verbatim. */
const checkDataset = (script: string): number =>
  run(process.execPath, [
    '--experimental-strip-types',
    `scripts/${script}`,
    '--check',
  ])

const refreshDataset = (script: string): number =>
  run(process.execPath, [
    '--experimental-strip-types',
    `scripts/${script}`,
    '--refresh',
  ])

type Outcome = 'current' | 'stale' | 'unreachable'

function classify(quests: number, diaries: number): Outcome {
  // Unreachable wins: if either fetch failed we learned nothing about either
  // dataset, and reporting the other as stale would be asserting more than we
  // checked.
  if (quests === EXIT_UNREACHABLE || diaries === EXIT_UNREACHABLE)
    return 'unreachable'
  if (quests === EXIT_FINDING || diaries === EXIT_FINDING) return 'stale'
  return 'current'
}

function prBody(quests: number, diaries: number, verified: boolean): string {
  const verdict = verified
    ? 'passed'
    : '**FAILED** — read the diff before merging'

  return [
    'The wiki has moved since these datasets were generated.',
    '',
    `- \`build:quests --check\` exited ${quests}`,
    `- \`build:diaries --check\` exited ${diaries}`,
    `- typecheck and tests: ${verdict}`,
    '',
    'Regenerated by `scripts/check-dataset-drift.ts`. **Read the diff rather',
    'than merging on the green tick** — the wiki is world-editable, so this is',
    "the one path by which someone else's edit reaches production, and a parser",
    'regression looks like a clean exit code and an obvious diff.',
    '',
    'Merging this does not deploy: `chore:` carries no release, so the running',
    'app keeps its current data until the next release or a manual run of the',
    'Release workflow.',
  ].join('\n')
}

function openPullRequest(body: string): void {
  // Both datasets carry a `generatedAt` date, so an unchanged tree here means
  // regeneration produced byte-identical output — in practice a second run on
  // the same day, after the first already opened the PR. It is not a test for
  // "the wiki edit didn't matter"; that edit still moves the date.
  if (run('git', ['diff', '--quiet', '--', 'src/data']) === 0) {
    notice(
      'Regenerating changed nothing. The refresh PR is already up to date.',
    )
    return
  }

  run('git', ['config', 'user.name', 'github-actions[bot]'])
  run('git', [
    'config',
    'user.email',
    '41898282+github-actions[bot]@users.noreply.github.com',
  ])

  // One reused branch, force-pushed, so there is at most one open PR that
  // updates itself rather than a pile of dated ones.
  run('git', ['checkout', '-B', BRANCH])
  run('git', ['add', 'src/data'])
  run('git', ['commit', '-m', TITLE])
  run('git', ['push', '--force', 'origin', BRANCH])

  const existing = capture('gh', [
    'pr',
    'list',
    '--head',
    BRANCH,
    '--state',
    'open',
    '--json',
    'number',
    '--jq',
    '.[0].number',
  ])

  if (existing) {
    run('gh', ['pr', 'edit', existing, '--body', body])
    notice(`Updated the existing dataset refresh PR (#${existing}).`)
    return
  }

  run('gh', [
    'pr',
    'create',
    '--base',
    'main',
    '--head',
    BRANCH,
    '--title',
    TITLE,
    '--body',
    body,
  ])
}

function main(): void {
  const openPr = process.argv.includes('--open-pr')

  const quests = checkDataset('build-quests.ts')
  const diaries = checkDataset('build-diaries.ts')
  const outcome = classify(quests, diaries)

  if (outcome === 'unreachable') {
    // Not a finding, so not a failure. A volunteer-run wiki being down on a
    // Thursday says nothing about our data, and a job that goes red for it is
    // a job people stop reading.
    notice(
      'The wiki could not be reached. No conclusion about the datasets; ' +
        'trying again next week.',
    )
    process.exitCode = EXIT_OK
    return
  }

  if (outcome === 'current') {
    notice('Both datasets match the wiki.')
    process.exitCode = EXIT_OK
    return
  }

  if (!openPr) {
    notice(
      `Stale: build-quests exited ${quests}, build-diaries exited ${diaries}. ` +
        'Re-run with --open-pr to regenerate and raise a PR.',
    )
    process.exitCode = EXIT_FINDING
    return
  }

  /*
   * Quests first: build-diaries resolves every diary prerequisite against
   * quests.json and fails loud on one it cannot find, so running it against a
   * stale quest list turns a renamed quest into a failed diary build.
   *
   * Both fail loud by design, so a non-zero here means the parser met
   * something new — a different finding from "the wiki moved", and one that
   * wants a person at the parser rather than a merge button. Left to fail the
   * run rather than swallowed.
   */
  for (const script of ['build-quests.ts', 'build-diaries.ts']) {
    const code = refreshDataset(script)
    if (code !== 0) {
      console.error(`\n${script} failed to regenerate (exit ${code}).`)
      process.exitCode = code
      return
    }
  }

  /*
   * Verified here rather than by CI on the resulting PR: GitHub does not
   * trigger workflows from events created by GITHUB_TOKEN, so that PR would
   * sit with no checks unless this job carried a long-lived PAT with write
   * access. Running them inline is both simpler and less to leak.
   *
   * `npm test` is the one that earns its place — the committed-dataset test
   * walks the regenerated data and fails if a prerequisite stops resolving or
   * two task ids collide.
   */
  const verified =
    run('npm', ['run', 'typecheck']) === 0 && run('npm', ['test']) === 0

  openPullRequest(prBody(quests, diaries, verified))

  // Deliberately not a failure when `verified` is false: the PR is more useful
  // than a red run, and its body carries the verdict where it will be read.
  process.exitCode = EXIT_OK
}

main()
