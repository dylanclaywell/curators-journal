/**
 * Vendors the icons we actually use into src/lib/icons.ts.
 *
 * Two sources, two jobs:
 *   game-icons.net (CC BY 3.0) — domain concepts: quests, locks, hourglasses.
 *   Phosphor (MIT)            — interface chrome: charts, checks, gears.
 *
 * Vendoring rather than depending: the whole set is ~10 icons, the app has to
 * work offline, and a committed module is diffable. Re-run after editing the
 * ICONS list:  npm run build:icons
 *
 * game-icons ship as a 512x512 black background rect plus a white foreground
 * path. Both get normalized here: background dropped, fill handed to
 * currentColor at the render site.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))

/** The background plate game-icons draws behind every glyph. */
const GAME_ICON_BG = /<path\s+d="M0 0h512v512H0z"\s*\/>/

/*
 * Pick SOLID silhouettes, not line drawings.
 *
 * game-icons are drawn on a 512 grid for large display. A line-based glyph's
 * strokes are ~18 units, which is 0.7px at tab-bar size — it renders as a grey
 * smudge. `checklist` was exactly this mistake; `scroll-unfurled` carries the
 * same meaning as a filled shape and stays crisp at 20px.
 */
const ICONS = [
  // key, source file (relative to root), attribution group
  ['scroll', 'src/assets/icons/scroll-unfurled.svg', 'game-icons'],
  ['hourglass', 'src/assets/icons/hourglass.svg', 'game-icons'],
  ['padlock', 'src/assets/icons/padlock.svg', 'game-icons'],
  ['openBook', 'src/assets/icons/open-book.svg', 'game-icons'],
  [
    'chart',
    'node_modules/@phosphor-icons/core/assets/bold/chart-bar-bold.svg',
    'phosphor',
  ],
  [
    'check',
    'node_modules/@phosphor-icons/core/assets/bold/check-bold.svg',
    'phosphor',
  ],
  [
    'gear',
    'node_modules/@phosphor-icons/core/assets/bold/gear-bold.svg',
    'phosphor',
  ],
  [
    'external',
    'node_modules/@phosphor-icons/core/assets/bold/arrow-square-out-bold.svg',
    'phosphor',
  ],
  [
    'search',
    'node_modules/@phosphor-icons/core/assets/bold/magnifying-glass-bold.svg',
    'phosphor',
  ],
  [
    'plus',
    'node_modules/@phosphor-icons/core/assets/bold/plus-bold.svg',
    'phosphor',
  ],
]

/** Pulls the viewBox and every path `d` out of one SVG file. */
function parse(svg, key) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`${key}: no viewBox`)

  // Drop game-icons' background plate before collecting paths, or the glyph
  // renders as a filled square.
  const body = svg.replace(GAME_ICON_BG, '')

  const paths = [...body.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) throw new Error(`${key}: no path data`)

  // Subpaths concatenate, so several <path> elements collapse into one `d`.
  // This holds only because every icon here is a flat single-color glyph —
  // it would silently merge layers on a multi-color icon.
  return { viewBox, path: paths.join(' ') }
}

const entries = []
const credits = { 'game-icons': [], phosphor: [] }

for (const [key, file, group] of ICONS) {
  const svg = await readFile(`${root}${file}`, 'utf8')
  const { viewBox, path } = parse(svg, key)
  entries.push({ key, viewBox, path })
  credits[group].push(key)
  console.log(`${key.padEnd(10)} ${viewBox.padEnd(13)} ${path.length} chars`)
}

const ts = `/**
 * Generated by scripts/build-icon-set.mjs — do not edit by hand.
 *
 * Domain icons (${credits['game-icons'].join(', ')}) are from
 * game-icons.net, licensed CC BY 3.0. Interface icons
 * (${credits.phosphor.join(', ')}) are from Phosphor, licensed MIT.
 * Attribution for both ships in the app's About panel and the README.
 *
 * Icons carry their own viewBox because the two packs draw on different
 * grids (512 vs 256) — never assume 24.
 */

export interface IconDef {
  viewBox: string
  /** Flat single-color glyph, filled with currentColor at the render site. */
  path: string
}

export const icons = {
${entries.map((e) => `  ${e.key}: {\n    viewBox: '${e.viewBox}',\n    path: '${e.path}',\n  },`).join('\n')}
} satisfies Record<string, IconDef>

export type IconName = keyof typeof icons
`

await writeFile(`${root}src/lib/icons.ts`, ts)
console.log(`\nwrote src/lib/icons.ts (${(ts.length / 1024).toFixed(1)} KB)`)
